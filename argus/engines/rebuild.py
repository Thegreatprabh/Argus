"""Rebuild engine: blueprint -> starter codebase.

This is ARGUS's signature move. REA explains how software works;
ARGUS also generates the *starting point of your own version*:

    web URL / APK  ->  blueprint  ->  project scaffold you own

Honest scope: a clean, working *starter* — structure, API clients,
page shells, and notes on what needs manual work. Not a pixel-perfect
clone (no tool can recover original source from a build).
"""

from __future__ import annotations

import re
from pathlib import Path
from typing import Any, Dict, List
from urllib.parse import urlparse

from . import web as webmod
from .base import Engine, EngineResult, Finding
from .mobile import MobileEngine

HREF_RE = re.compile(r"""href=['"](/[^'"#?]*)['"]""", re.IGNORECASE)


def _slug(url: str) -> str:
    p = urlparse(url).path.strip("/").replace("/", "-")
    return re.sub(r"[^a-z0-9\-]", "", p.lower()) or "index"


def _fn_name(endpoint: str) -> str:
    ep = re.sub(r"^https?://[^/]+", "", endpoint)
    parts = [p for p in re.split(r"[^a-z0-9]+", ep.lower()) if p]
    junk = {"api", "v1", "v2", "v3", "rest", "graphql"}
    parts = [p for p in parts if p not in junk][:4]
    return "call_" + ("_".join(parts) or "endpoint")


class RebuildEngine(Engine):
    name = "rebuild"

    # -- blueprint ------------------------------------------------------
    def blueprint_web(self, url: str) -> Dict[str, Any]:
        res = webmod.WebEngine().analyze(url, deep=True).to_dict()
        pages = [{"url": url, "slug": "index"}]
        try:
            html = webmod._fetch(url)
            host = urlparse(url).netloc
            seen = {url}
            for href in HREF_RE.findall(html):
                full = webmod.urljoin(url, href)
                if urlparse(full).netloc == host and full not in seen:
                    seen.add(full)
                    pages.append({"url": full, "slug": _slug(full)})
                if len(pages) >= 8:
                    break
        except Exception:
            pass
        return {
            "kind": "web",
            "source": url,
            "tech": res["raw"].get("tech", []),
            "pages": pages,
            "endpoints": res["raw"].get("endpoints", []),
            "forms": res["raw"].get("forms", []),
            "findings": res["findings"],
        }

    def blueprint_apk(self, path: str) -> Dict[str, Any]:
        res = MobileEngine().analyze(path).to_dict()
        raw = res["raw"]
        return {
            "kind": "apk",
            "source": path,
            "permissions": raw.get("permissions", []),
            "dangerous": raw.get("dangerous", []),
            "sdks": raw.get("sdks", []),
            "urls": raw.get("urls", []),
            "findings": res["findings"],
        }

    # -- generation ------------------------------------------------------
    def generate(self, bp: Dict[str, Any], outdir: str | Path,
                 project: str = "my-rebuild") -> List[str]:
        out = Path(outdir)
        out.mkdir(parents=True, exist_ok=True)
        written: List[str] = []
        kind = bp.get("kind")

        def w(rel: str, text: str) -> None:
            p = out / rel
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_text(text)
            written.append(rel)

        if kind == "web":
            endpoints: List[str] = bp.get("endpoints", [])
            fns = []
            for ep in endpoints[:40]:
                name = _fn_name(ep)
                fns.append(
                    f"// {ep}\n"
                    f"export async function {name}(params = {{}}) {{\n"
                    f"  const res = await fetch({ep!r}, {{\n"
                    f"    method: 'GET', headers: {{ 'Content-Type': 'application/json' }},\n"
                    f"  }});\n"
                    f"  if (!res.ok) throw new Error(`${{res.status}} on {ep}`);\n"
                    f"  return res.json();\n"
                    f"}}\n")
            w("src/api.js",
              "// API clients auto-generated by ARGUS rebuild.\n"
              "// TODO: set methods/bodies/auth per REBUILD_NOTES.md\n\n"
              + "\n".join(fns) or "// (no endpoints discovered)\n")
            nav = "\n".join(
                f'    <li><a href="pages/{p["slug"]}.html">{p["slug"]}</a></li>'
                for p in bp.get("pages", []))
            w("index.html",
              "<!doctype html>\n<html><head><meta charset='utf-8'>\n"
              f"<title>{project}</title>\n"
              "<link rel='stylesheet' href='src/styles.css'></head><body>\n"
              f"<h1>{project}</h1>\n"
              f"<p>Rebuilt with ARGUS from {bp.get('source')}</p>\n"
              f"<nav><ul>\n{nav}\n</ul></nav>\n"
              "<script type='module' src='src/app.js'></script>\n"
              "</body></html>\n")
            for p in bp.get("pages", [])[1:]:
                w(f"pages/{p['slug']}.html",
                  "<!doctype html>\n<html><head><meta charset='utf-8'>\n"
                  f"<title>{p['slug']}</title>\n"
                  "<link rel='stylesheet' href='../src/styles.css'></head>"
                  "<body>\n"
                  f"<!-- TODO: rebuild layout of {p['url']} -->\n"
                  "<h1>TODO</h1>\n</body></html>\n")
            w("src/styles.css",
              "/* Starter styles — replace with your design system */\n"
              "body { font-family: system-ui, sans-serif; margin: 2rem; }\n")
            w("src/app.js",
              "import * as api from './api.js';\n"
              "// TODO: wire UI events to api.* calls\n"
              "console.log('ARGUS rebuild scaffold ready');\n")
        elif kind == "apk":
            w("FEATURES.md",
              f"# Feature map — rebuilt from {bp.get('source')}\n\n"
              "## Permissions\n" +
              "".join(f"- {p}\n" for p in bp.get("permissions", [])) +
              "\n## Network surface\n" +
              "".join(f"- {u}\n" for u in bp.get("urls", [])[:50]) +
              "\n## Embedded SDKs\n" +
              "".join(f"- {s}\n" for s in bp.get("sdks", [])))
            w("src/api.js",
              "// TODO: implement clients for discovered endpoints\n" +
              "".join(f"// {u}\n" for u in bp.get("urls", [])[:40]))

        w("REBUILD_NOTES.md",
          f"# Rebuild notes — {project}\n\n"
          f"Source: `{bp.get('source')}`\n"
          f"Generated by ARGUS rebuild engine (starter scaffold, not a 1:1 clone).\n\n"
          "## What was recovered\n" +
          "".join(f"- {f['title']}: {f['evidence'][:160]}\n"
                  for f in bp.get("findings", [])) +
          "\n## Manual work needed\n"
          "- [ ] Verify each API endpoint (method, auth, payloads)\n"
          "- [ ] Recreate visual design with your own assets\n"
          "- [ ] Replace placeholder copy/images (never reuse licensed media)\n"
          "- [ ] Implement business logic the static scan can't see\n")
        w("README.md",
          f"# {project}\n\nStarter codebase generated by **ARGUS** "
          f"from `{bp.get('source')}`.\n\n"
          "This is original code written from an analysis blueprint — "
          "a clean-room rebuild, not a copy.\n")
        return written

    # -- Engine interface -------------------------------------------------
    def analyze(self, target: str, **options: Any) -> EngineResult:
        result = EngineResult(target=target, engine=self.name)
        outdir = options.get("outdir", "rebuild-out")
        project = options.get("project", "my-rebuild")
        bp = (self.blueprint_apk(target) if target.lower().endswith(".apk")
              else self.blueprint_web(target))
        files = self.generate(bp, outdir, project)
        result.findings.append(Finding(
            f"Rebuild scaffold generated ({len(files)} files)",
            f"Project '{project}' written to {outdir}/",
            meta={"files": files, "blueprint": bp},
        ))
        result.raw = {"blueprint": bp, "files": files}
        return result
